-- Stable entry identity supports duplicate songs and complete-list reorders.
ALTER TABLE public.setlist_songs
    ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE public.setlist_songs
    ADD CONSTRAINT setlist_songs_id_key UNIQUE (id);

-- Idempotency receipts let a client safely retry after the server committed
-- an operation but its response was lost. Keep receipts after resource delete.
CREATE TABLE public.mutation_receipts (
    operation_id uuid PRIMARY KEY,
    request_hash text NOT NULL,
    entity_type text NOT NULL CHECK (entity_type IN ('song', 'setlist')),
    resource_id text,
    response jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE OR REPLACE FUNCTION public.set_setlist_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = GREATEST(clock_timestamp(), OLD.updated_at + INTERVAL '1 microsecond');
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER setlists_set_updated_at ON public.setlists;
CREATE TRIGGER setlists_set_updated_at
    BEFORE UPDATE ON public.setlists
    FOR EACH ROW EXECUTE FUNCTION public.set_setlist_updated_at();

CREATE OR REPLACE FUNCTION public.bump_entry_parent_version() RETURNS TRIGGER AS $$
DECLARE
    affected_setlist_id integer;
BEGIN
    IF TG_OP = 'DELETE' THEN
        affected_setlist_id := OLD.setlist_id;
    ELSE
        affected_setlist_id := NEW.setlist_id;
    END IF;
    UPDATE public.setlists SET updated_at = updated_at WHERE id = affected_setlist_id;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER setlist_songs_bump_parent_version
    AFTER INSERT OR UPDATE OR DELETE ON public.setlist_songs
    FOR EACH ROW EXECUTE FUNCTION public.bump_entry_parent_version();
